import { jsPDF } from 'jspdf';
import { AuthUser, ExamResultItem } from '../types/index.ts';

export function formatDuration(seconds: number): string {
  const s = Math.max(0, Math.floor(seconds));
  const hrs = Math.floor(s / 3600);
  const mins = Math.floor((s % 3600) / 60);
  const secs = s % 60;
  return [hrs, mins, secs].map((v) => String(v).padStart(2, '0')).join(':');
}

export function downloadResultPdf(result: ExamResultItem, student: AuthUser): void {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });

  // Navy header banner
  doc.setFillColor(15, 36, 71);
  doc.rect(0, 0, 595, 92, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(20);
  doc.text('ACADET JAMB CBT', 40, 42);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  doc.text('Official UTME Practice & Examination Performance Report', 40, 64);

  // Candidate Details
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text('Candidate Details', 40, 130);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10.5);
  doc.text(`Full Name: ${student.fullName}`, 40, 152);
  doc.text(`Registration No: ${student.registrationNumber || 'N/A'}`, 320, 152);
  doc.text(`Target JAMB Year: ${student.jambYear || 2026}`, 40, 170);
  doc.text(`Intended Course: ${student.intendedCourse || 'N/A'}`, 320, 170);
  doc.text(`Examination: ${result.examTitle}`, 40, 188);
  doc.text(`Submitted At: ${new Date(result.createdAt).toLocaleString()}`, 40, 206);

  // Summary Score Box
  doc.setFillColor(241, 245, 249);
  doc.roundedRect(40, 228, 515, 72, 6, 6, 'F');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(30, 64, 175);
  doc.text('UTME SCALED SCORE', 60, 252);
  doc.setFontSize(22);
  doc.text(`${result.scoreOutOf400} / 400`, 60, 280);

  doc.setTextColor(5, 150, 105);
  doc.setFontSize(11);
  doc.text('PERCENTAGE', 235, 252);
  doc.setFontSize(22);
  doc.text(`${Number(result.percentage).toFixed(1)}%`, 235, 280);

  doc.setTextColor(15, 23, 42);
  doc.setFontSize(11);
  doc.text('QUESTIONS', 395, 252);
  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');
  doc.text(`Correct: ${result.correctCount}  |  Wrong: ${result.wrongCount}`, 395, 270);
  doc.text(`Unanswered: ${result.unansweredCount}  |  Time: ${formatDuration(result.timeSpentSeconds)}`, 395, 286);

  // Subject Breakdown Table
  let y = 338;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text('Subject-by-Subject Breakdown', 40, y);
  y += 18;

  doc.setFillColor(15, 36, 71);
  doc.rect(40, y, 515, 24, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(10);
  doc.text('Subject', 52, y + 16);
  doc.text('Total', 270, y + 16);
  doc.text('Correct', 330, y + 16);
  doc.text('Wrong', 395, y + 16);
  doc.text('Accuracy', 475, y + 16);
  y += 24;

  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'normal');
  for (const sub of result.subjectBreakdown || []) {
    doc.setDrawColor(226, 232, 240);
    doc.line(40, y + 24, 555, y + 24);
    doc.text(`${sub.subjectName} (${sub.subjectCode})`, 52, y + 16);
    doc.text(String(sub.totalQuestions), 270, y + 16);
    doc.text(String(sub.correctCount), 330, y + 16);
    doc.text(String(sub.wrongCount), 395, y + 16);
    doc.text(`${Number(sub.percentage).toFixed(1)}%`, 475, y + 16);
    y += 26;
  }

  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  doc.text('Generated by Acadet JAMB CBT Platform. Keep practicing for UTME excellence.', 40, 790);

  doc.save(`Acadet-JAMB-Result-${student.registrationNumber || result.id.slice(0, 8)}.pdf`);
}
